"""frozen-corpus — regression testing for systems whose output is a judgment.

Unit tests answer "is this function right?". This answers a different question:
"did anything move that I did not mean to move?"

That question matters when a system makes thousands of small judgments — a score, a
ranking, a recommendation, a refusal and the sentence explaining it — and a change
to any part of it can quietly shift a number three screens away. You cannot assert
your way to that. You have to record what it said, change the code, and look.

The whole library is: run a function over a fixed corpus, write every answer to a
file, and diff that file against the one from last time.

What makes it worth a library rather than a script is the discipline around it:
freezing the clock, stubbing the network, pinning the seed, and refusing to let a
baseline be regenerated by accident. Those four are what separate a regression
harness from a file full of numbers nobody trusts.
"""

